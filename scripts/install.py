#!/usr/bin/env python3
"""Install user configuration, keeping one complete snapshot per invocation."""
import datetime
import json
import os
from pathlib import Path
import shutil

project = Path(__file__).resolve().parents[1]
home = Path.home()
config = Path(os.environ.get('XDG_CONFIG_HOME', home / '.config'))
state = Path(os.environ.get('XDG_STATE_HOME', home / '.local/state')) / 'dark-mountain'
backup = state / 'backups' / datetime.datetime.now().strftime('%Y%m%d-%H%M%S-%f')
targets = [config/'hypr/hyprland.lua', config/'hypr/dark-mountain.lua',
           config/'kitty/kitty.conf', config/'kitty/dark-mountain.conf',
           config/'quickshell/dark-mountain', home/'.local/bin/dark-mountain',
           config/'uwsm/env', config/'environment.d/60-dark-mountain-timezone.conf']
if not targets[0].is_file():
    raise SystemExit('Configuração Lua do Hyprland não encontrada: '+str(targets[0]))
backup.mkdir(parents=True)
manifest = []
for i, target in enumerate(targets):
    exists = target.exists() or target.is_symlink()
    manifest.append({'path': str(target), 'saved': str(i) if exists else None})
    if exists:
        if target.is_symlink():
            (backup/str(i)).symlink_to(os.readlink(target))
        elif target.is_dir():
            shutil.copytree(target, backup/str(i), symlinks=True)
        else:
            shutil.copy2(target, backup/str(i))
(backup/'manifest.json').write_text(json.dumps(manifest, indent=2))
for target in targets:
    target.parent.mkdir(parents=True, exist_ok=True)
for source, target in [(project/'hypr/theme.lua', targets[1]), (project/'kitty/theme.conf', targets[3]),
                       (project/'quickshell', targets[4]), (project/'scripts/dark-mountain', targets[5])]:
    if target.is_symlink() or target.is_file(): target.unlink()
    elif target.is_dir(): shutil.rmtree(target)
    target.symlink_to(source, target_is_directory=source.is_dir())
line = 'dofile(os.getenv("XDG_CONFIG_HOME") and (os.getenv("XDG_CONFIG_HOME") .. "/hypr/dark-mountain.lua") or (os.getenv("HOME") .. "/.config/hypr/dark-mountain.lua"))'
hypr = targets[0].read_text()
# Remove the stock generated-config warning only; retain all existing bindings.
hypr = hypr.replace('hl.config({ autogenerated = true })', 'hl.config({ autogenerated = false })')
if line not in hypr: hypr += '\n-- Dark Mountain\n' + line + '\n'
targets[0].write_text(hypr)
kitty = targets[2].read_text() if targets[2].exists() else ''
if 'include dark-mountain.conf' not in kitty:
    targets[2].write_text(kitty + '\n# Dark Mountain\ninclude dark-mountain.conf\n')
session_env = targets[6].read_text() if targets[6].exists() else ''
if 'export TZ=America/Sao_Paulo' not in session_env:
    targets[6].write_text(session_env + '\n# Brasília\nexport TZ=America/Sao_Paulo\n')
targets[7].write_text('TZ=America/Sao_Paulo\n')
(state/'latest-backup').write_text(str(backup))
print('Rice instalado. Backup:', backup)
print('Ativar: hyprctl reload && ~/.local/bin/dark-mountain start')
