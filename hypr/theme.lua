-- Dark Mountain: loaded after the existing Hyprland configuration.
hl.config({
    input = { kb_layout = "br", kb_variant = "", kb_model = "abnt2" },
    general = {
        gaps_in = 2, gaps_out = 2, border_size = 1,
        col = { active_border = "rgba(303030ff)", inactive_border = "rgba(303030ff)" },
    },
    decoration = {
        rounding = 6,
        shadow = { enabled = true, range = 12, render_power = 3, color = 0x99000000 },
        blur = { enabled = true, size = 5, passes = 2 },
    },
    misc = { disable_hyprland_logo = true, force_default_wallpaper = 0 },
})
-- Own curve: no dependency on curves from a machine-specific base config.
hl.curve("darkMountainEaseOutQuint", { type = "bezier", points = { {0.23, 1}, {0.32, 1} } })
hl.animation({ leaf = "windows", enabled = true, speed = 3, bezier = "darkMountainEaseOutQuint" })
hl.animation({ leaf = "workspaces", enabled = true, speed = 2, bezier = "darkMountainEaseOutQuint", style = "fade" })
hl.on("hyprland.start", function()
    hl.exec_cmd(os.getenv("HOME") .. "/.local/bin/dark-mountain start")
end)

-- Keep output names, resolution, refresh rate and scale from the base Hyprland config.
-- This supports physical monitors and laptops without a VM-specific override.

-- Brasília for applications launched by Hyprland.
hl.env("TZ", "America/Sao_Paulo")

-- Persisted palette, generated by the local theme controller.
local themeState = os.getenv("XDG_STATE_HOME") or (os.getenv("HOME") .. "/.local/state")
pcall(dofile, themeState .. "/dark-mountain/colors.lua")

local riceCommand = os.getenv("HOME") .. "/.local/bin/dark-mountain"
hl.bind("SUPER + SHIFT + T", hl.dsp.exec_cmd(riceCommand .. " theme"))
hl.bind("SUPER + SHIFT + W", hl.dsp.exec_cmd(riceCommand .. " wallpaper"))
hl.bind("SUPER + SHIFT + B", hl.dsp.exec_cmd(riceCommand .. " focus"))
hl.bind("SUPER + SHIFT + P", hl.dsp.exec_cmd(riceCommand .. " power"))

-- Aplicativos e utilitários do rice (sem alterar os atalhos anteriores).
local tools = os.getenv("HOME") .. "/.local/bin/rice-tools"
hl.bind("SUPER + SPACE", hl.dsp.exec_cmd(tools .. " apps"))
hl.bind("SUPER + N", hl.dsp.exec_cmd(tools .. " terminal nvim"))
hl.bind("SUPER + D", hl.dsp.exec_cmd(tools .. " terminal lazydocker"))
hl.bind("SUPER + T", hl.dsp.exec_cmd(tools .. " terminal tmux new-session -A -s main"))
hl.bind("SUPER + F", hl.dsp.exec_cmd(tools .. " terminal yazi"))
hl.bind("SUPER + SHIFT + V", hl.dsp.exec_cmd(tools .. " clipboard"))
hl.bind("Print", hl.dsp.exec_cmd(tools .. " shot"))
hl.bind("SHIFT + Print", hl.dsp.exec_cmd(tools .. " shot full"))
hl.bind("SUPER + SHIFT + R", hl.dsp.exec_cmd(tools .. " record"))
hl.env("EDITOR", "nvim")
hl.env("VISUAL", "nvim")
hl.on("hyprland.start", function()
    hl.exec_cmd("systemctl --user start rice-clipboard.service")
end)

-- Encerramento de janela e sessão (sessão exige confirmação na Island).
hl.bind("SUPER + SHIFT + Q", hl.dsp.window.close())
hl.bind("SUPER + CTRL + SHIFT + Q", hl.dsp.exec_cmd(riceCommand .. " logout"))

-- Blur the translucent Island surface, including its expanded panels.
hl.layer_rule({
    name = "dark-mountain-island-blur",
    match = { namespace = "^dark-mountain-island$" },
    blur = true,
    ignore_alpha = 0.01,
})
hl.bind("SUPER + CTRL + B", hl.dsp.exec_cmd(tools .. " terminal btop"))
